// Compiles a bellingua XLIFF export (one <module>.xlf per Steam loc module) into the
// translation table bundled with the plugin: frontend/generated/translations.ts.
// Usage: npm run compile [-- --in <dir>] [--min-state mt|translated|approved]
// Reads translations/be (the committed bellingua export) and its source snapshot translations/be/source.
// npm run build / npm run pack run this first, so a plugin build always uses the latest export.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { parseArgs } from "node:util";
import type { CompiledTranslations } from "../frontend/patch.ts";
import type { SourceEntry } from "./extract.ts";
import { plain } from "./lib/placeholders.ts";
import { readXliff, type Problem, type XliffFile } from "./lib/xliff.ts";

export type MinState = "mt" | "translated" | "approved";
const MIN_RANK: Record<MinState, number> = { mt: 1, translated: 2, approved: 3 };

/** Module order for ids defined in several modules: the first one is the default. */
const MODULE_PRIORITY = ["steamui", "shared", "friendsui", "steampops"];

/** Mirrors bellingua's model.FromXLIFFState: 1 = machine, 2 = translated, 3 = approved. */
export function stateRank(state: string | undefined): number {
  switch (state) {
    case "translated":
    case "needs-review-l10n":
    case "needs-l10n":
    case "needs-adaptation":
    case "needs-review-adaptation":
      return 2;
    case "final":
    case "signed-off":
      return 3;
    default:
      return 1;
  }
}

export interface CompileReport {
  modules: Record<string, { units: number; shipped: number }>;
  unknownIds: string[];
  problems: string[];
}

export function compileTranslations(
  files: XliffFile[],
  sources: Record<string, Record<string, SourceEntry>>,
  minState: MinState,
): { data: CompiledTranslations; report: CompileReport } {
  const report: CompileReport = { modules: {}, unknownIds: [], problems: [] };
  const rank = (m: string) => {
    const i = MODULE_PRIORITY.indexOf(m);
    return i < 0 ? MODULE_PRIORITY.length : i;
  };
  const candidates = new Map<string, { module: string; en: string | undefined; be: string }[]>();

  for (const f of [...files].sort((a, b) => rank(a.original) - rank(b.original))) {
    const source = sources[f.original];
    if (!source) throw new Error(`No extracted source for module "${f.original}"; run npm run extract`);
    const stats = { units: f.units.length, shipped: 0 };
    report.modules[f.original] = stats;
    for (const u of f.units) {
      if (!u.target || stateRank(u.state) < MIN_RANK[minState]) continue;
      const be = plain(u.target);
      if (!be) continue;
      const entry = source[u.id];
      if (!entry) {
        report.unknownIds.push(`${f.original}:${u.id}`);
        continue;
      }
      const list = candidates.get(u.id) ?? [];
      list.push({ module: f.original, en: entry.en, be });
      candidates.set(u.id, list);
      stats.shipped++;
    }
  }

  const data: CompiledTranslations = { tokens: {}, byEnglish: {} };
  for (const id of [...candidates.keys()].sort()) {
    const list = candidates.get(id)!;
    data.tokens[id] = list[0]!.be;
    const byEn = new Map<string, string>();
    for (const c of list) if (c.en !== undefined && !byEn.has(c.en)) byEn.set(c.en, c.be);
    if (byEn.size > 1 && new Set(byEn.values()).size > 1) data.byEnglish[id] = Object.fromEntries(byEn);
  }
  return { data, report };
}

/**
 * The bundled module. The table is one JSON.parse('…') string literal: V8 parses that
 * much faster than an equivalent object literal, which matters at ~1.7 MB.
 */
export function toModuleSource(data: CompiledTranslations): string {
  // JSON.stringify of the JSON text yields a valid JS string literal; also escape
  // U+2028/U+2029 for older parsers.
  // (Character codes instead of escapes keep this line safe from editors that decode them.)
  const [LS, PS, BS] = [0x2028, 0x2029, 0x5c].map((c) => String.fromCharCode(c)) as [string, string, string];
  const literal = JSON.stringify(JSON.stringify(data)).replaceAll(LS, `${BS}u2028`).replaceAll(PS, `${BS}u2029`);
  return (
    "// Generated by tools/compile.ts from the bellingua export. Do not edit.\n" +
    'import type { CompiledTranslations } from "../patch";\n' +
    `const translations: CompiledTranslations = JSON.parse(${literal});\n` +
    "export default translations;\n"
  );
}

function main() {
  const { values } = parseArgs({
    options: {
      in: { type: "string", default: join("translations", "be") },
      source: { type: "string", default: join("translations", "be", "source") },
      out: { type: "string", default: join("frontend", "generated", "translations.ts") },
      "min-state": { type: "string", default: "mt" },
    },
  });
  const minState = values["min-state"] as MinState;
  if (!(minState in MIN_RANK)) throw new Error(`--min-state must be one of ${Object.keys(MIN_RANK).join(", ")}`);
  if (!existsSync(values.in)) {
    throw new Error(`No bellingua export at ${values.in}. Pass --in <dir>.`);
  }

  const files: XliffFile[] = [];
  const problems: string[] = [];
  for (const name of readdirSync(values.in).filter((n) => n.endsWith(".xlf")).sort()) {
    const { file, problems: p } = readXliff(readFileSync(join(values.in, name), "utf8"));
    if (!file.original) file.original = basename(name, ".xlf");
    problems.push(...p.map((x: Problem) => `${name}:${x.id}: ${x.reason}`));
    files.push(file);
  }
  const sources = Object.fromEntries(
    files.map((f) => [f.original, JSON.parse(readFileSync(join(values.source, `${f.original}.json`), "utf8"))]),
  );

  const { data, report } = compileTranslations(files, sources, minState);
  report.problems = problems;
  mkdirSync(dirname(values.out), { recursive: true });
  writeFileSync(values.out, toModuleSource(data));

  console.log(`Export: ${values.in} (min state: ${minState})`);
  for (const [m, s] of Object.entries(report.modules)) {
    console.log(`${m.padEnd(12)} ${String(s.shipped).padStart(6)} / ${s.units} translations shipped`);
  }
  console.log(
    `${Object.keys(data.tokens).length} tokens, ${Object.keys(data.byEnglish).length} disambiguated by English → ${values.out}`,
  );
  if (report.unknownIds.length) console.warn(`Skipped ${report.unknownIds.length} ids Steam no longer has: ${report.unknownIds.slice(0, 10).join(", ")}`);
  if (problems.length) console.warn(`Rejected ${problems.length} targets with broken placeholders:\n  ${problems.slice(0, 20).join("\n  ")}`);
}

if (import.meta.main) main();
